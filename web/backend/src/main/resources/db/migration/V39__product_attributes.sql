-- P1.2 ridotto (ADR 0008): attributi personalizzati di prodotto, testuali o a elenco, definiti da UI.
-- Descrivono il prodotto senza generare varianti (glossario in DOMAIN_MODEL.md). Un attributo vale per
-- tutti i prodotti oppure per una categoria e le sue sottocategorie. Nessun dato esistente viene toccato.

create table product_attributes (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    code varchar(64) not null,
    code_canonical varchar(64) not null,
    label varchar(120) not null,
    type varchar(16) not null,
    category_id bigint,
    active boolean not null default true,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_product_attributes_code unique (code_canonical),
    constraint fk_product_attributes_category foreign key (category_id) references product_categories (id),
    constraint chk_product_attributes_code check (char_length(trim(code)) > 0 and code_canonical = lower(trim(code))),
    constraint chk_product_attributes_label check (char_length(trim(label)) > 0),
    constraint chk_product_attributes_type check (type in ('TEXT', 'LIST'))
);

create index idx_product_attributes_category on product_attributes (category_id);

create table product_attribute_options (
    attribute_id bigint not null,
    position integer not null,
    option_value varchar(120) not null,
    option_value_canonical varchar(120) not null,
    constraint pk_product_attribute_options primary key (attribute_id, position),
    constraint uk_product_attribute_options_value unique (attribute_id, option_value_canonical),
    constraint fk_product_attribute_options_attribute foreign key (attribute_id) references product_attributes (id) on delete cascade,
    constraint chk_product_attribute_options_position check (position >= 0),
    constraint chk_product_attribute_options_value check (char_length(trim(option_value)) > 0 and option_value_canonical = lower(trim(option_value)))
);

create table product_attribute_values (
    product_id bigint not null,
    attribute_id bigint not null,
    attribute_value varchar(200) not null,
    constraint pk_product_attribute_values primary key (product_id, attribute_id),
    constraint fk_product_attribute_values_product foreign key (product_id) references products (id) on delete cascade,
    constraint fk_product_attribute_values_attribute foreign key (attribute_id) references product_attributes (id),
    constraint chk_product_attribute_values_value check (char_length(trim(attribute_value)) > 0)
);

create index idx_product_attribute_values_attribute on product_attribute_values (attribute_id);
