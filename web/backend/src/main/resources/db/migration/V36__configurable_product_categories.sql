-- P1.1 (ADR 0008): categorie di prodotto configurabili e gerarchiche al posto dell'elenco fisso nel codice.
-- Ogni valore presente in products.category diventa una categoria radice; nessun prodotto resta senza categoria.

create table product_categories (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    code varchar(64) not null,
    code_canonical varchar(64) not null,
    name varchar(120) not null,
    name_canonical varchar(120) not null,
    parent_id bigint,
    parent_key bigint not null default 0,
    active boolean not null default true,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_product_categories_code unique (code_canonical),
    constraint uk_product_categories_sibling_name unique (parent_key, name_canonical),
    constraint fk_product_categories_parent foreign key (parent_id) references product_categories (id),
    constraint chk_product_categories_parent_key check ((parent_id is null and parent_key = 0) or (parent_id is not null and parent_key = parent_id)),
    constraint chk_product_categories_not_self check (parent_id is null or parent_id <> id),
    constraint chk_product_categories_code check (char_length(trim(code)) > 0 and code_canonical = lower(trim(code))),
    constraint chk_product_categories_name check (char_length(trim(name)) > 0 and name_canonical = lower(trim(name)))
);

create index idx_product_categories_parent on product_categories (parent_id);

insert into product_categories (code, code_canonical, name, name_canonical, parent_key, active, created_at, updated_at)
values ('HARDWARE', 'hardware', 'Hardware', 'hardware', 0, true, current_timestamp, current_timestamp);

insert into product_categories (code, code_canonical, name, name_canonical, parent_key, active, created_at, updated_at)
values ('SOFTWARE', 'software', 'Software', 'software', 0, true, current_timestamp, current_timestamp);

insert into product_categories (code, code_canonical, name, name_canonical, parent_key, active, created_at, updated_at)
select legacy.display_name, legacy.canonical_name, legacy.display_name, legacy.canonical_name, 0, true, current_timestamp, current_timestamp
from (
    select min(trim(category)) as display_name, lower(trim(category)) as canonical_name
    from products
    where lower(trim(category)) not in ('hardware', 'software')
    group by lower(trim(category))
) legacy;

alter table products add column category_id bigint;

update products
set category_id = (
    select c.id
    from product_categories c
    where c.code_canonical = lower(trim(products.category))
);

alter table products alter column category_id set not null;

alter table products add constraint fk_products_category foreign key (category_id) references product_categories (id);

create index idx_products_category on products (category_id);

alter table products drop column category;
