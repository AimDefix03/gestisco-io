-- P1.4 (ADR 0008): aliquote IVA per prodotto, fotografate sulla riga d'ordine e riepilogate per aliquota nei documenti.
-- I prezzi restano IVA inclusa; lo storico mantiene l'aliquota aziendale con cui e stato calcolato.

create table vat_rates (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    code varchar(16) not null,
    rate numeric(5, 4) not null,
    nature varchar(8),
    description varchar(160) not null,
    default_rate boolean not null default false,
    active boolean not null default true,
    sort_order integer not null default 0,
    constraint uk_vat_rates_code unique (code),
    constraint chk_vat_rates_rate check (rate >= 0 and rate < 1),
    constraint chk_vat_rates_nature check ((rate > 0 and nature is null) or (rate = 0 and char_length(trim(nature)) > 0)),
    constraint chk_vat_rates_description check (char_length(trim(description)) > 0)
);

insert into vat_rates (code, rate, nature, description, sort_order) values ('IVA22', 0.2200, null, 'IVA 22% ordinaria', 10);
insert into vat_rates (code, rate, nature, description, sort_order) values ('IVA10', 0.1000, null, 'IVA 10% ridotta', 20);
insert into vat_rates (code, rate, nature, description, sort_order) values ('IVA5', 0.0500, null, 'IVA 5% ridotta', 30);
insert into vat_rates (code, rate, nature, description, sort_order) values ('IVA4', 0.0400, null, 'IVA 4% minima', 40);
insert into vat_rates (code, rate, nature, description, sort_order) values ('ESENTE', 0.0000, 'N4', 'Esente', 50);

-- L'aliquota aziendale storica diventa quella predefinita; se non e tra le standard viene aggiunta.
insert into vat_rates (code, rate, nature, description, sort_order)
select 'AZIENDA', s.default_vat_rate, case when s.default_vat_rate = 0 then 'N4' else null end, 'Aliquota aziendale storica', 60
from company_settings s
where s.id = 1 and s.default_vat_rate not in (0.2200, 0.1000, 0.0500, 0.0400, 0.0000);

update vat_rates set default_rate = true
where id = (
    select min(v.id) from vat_rates v
    where v.rate = coalesce((select s.default_vat_rate from company_settings s where s.id = 1), 0.2200)
);

alter table products add column vat_rate_id bigint;
update products set vat_rate_id = (select id from vat_rates where default_rate = true);
alter table products alter column vat_rate_id set not null;
alter table products add constraint fk_products_vat_rate foreign key (vat_rate_id) references vat_rates (id);
create index idx_products_vat_rate on products (vat_rate_id);

-- Righe d'ordine: aliquota fotografata alla vendita; lo storico prende l'aliquota aziendale.
alter table order_items add column vat_rate numeric(5, 4);
alter table order_items add column vat_nature varchar(8);
update order_items set vat_rate = (select rate from vat_rates where default_rate = true),
                       vat_nature = (select nature from vat_rates where default_rate = true);
alter table order_items alter column vat_rate set not null;
alter table order_items add constraint chk_order_items_vat_rate check (vat_rate >= 0 and vat_rate < 1);

-- Righe documento: stessa fotografia, ricavata dal documento storico.
alter table fiscal_document_lines add column vat_rate numeric(5, 4);
alter table fiscal_document_lines add column vat_nature varchar(8);
update fiscal_document_lines set vat_rate = (select d.vat_rate from fiscal_documents d where d.id = fiscal_document_lines.document_id);
alter table fiscal_document_lines alter column vat_rate set not null;

-- Riepilogo IVA per aliquota; un documento con aliquote miste non ha un'unica vat_rate.
create table fiscal_document_vat_summaries (
    id bigint generated by default as identity primary key,
    document_id bigint not null,
    vat_rate numeric(5, 4) not null,
    vat_nature varchar(8),
    taxable_amount numeric(12, 2) not null,
    vat_amount numeric(12, 2) not null,
    total_amount numeric(12, 2) not null,
    constraint fk_fiscal_document_vat_summaries_document foreign key (document_id) references fiscal_documents (id),
    constraint chk_fiscal_document_vat_summaries_rate check (vat_rate >= 0 and vat_rate < 1),
    constraint chk_fiscal_document_vat_summaries_amounts check (taxable_amount >= 0 and vat_amount >= 0 and total_amount = taxable_amount + vat_amount)
);

create index idx_fiscal_document_vat_summaries_document on fiscal_document_vat_summaries (document_id);

insert into fiscal_document_vat_summaries (document_id, vat_rate, vat_nature, taxable_amount, vat_amount, total_amount)
select id, vat_rate, null, taxable_amount, vat_amount, taxable_amount + vat_amount
from fiscal_documents;

alter table fiscal_documents alter column vat_rate drop not null;
