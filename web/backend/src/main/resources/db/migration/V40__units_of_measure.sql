-- P1.7 (gate G1, ADR 0008): unita di misura configurabili da UI al posto dell'elenco fisso nel codice.
-- Le sei unita di V37 diventano le voci iniziali; i prodotti conservano il codice gia salvato,
-- ora garantito da una chiave esterna invece che dal vincolo sull'elenco. PIECE resta l'unita base.

create table units_of_measure (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    code varchar(16) not null,
    label varchar(60) not null,
    symbol varchar(12) not null,
    active boolean not null default true,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_units_of_measure_code unique (code),
    constraint chk_units_of_measure_code check (char_length(trim(code)) > 0 and code = upper(trim(code))),
    constraint chk_units_of_measure_label check (char_length(trim(label)) > 0),
    constraint chk_units_of_measure_symbol check (char_length(trim(symbol)) > 0),
    constraint chk_units_of_measure_base_active check (code <> 'PIECE' or active)
);

